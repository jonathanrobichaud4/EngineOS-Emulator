#!/usr/bin/env python3
"""The deck models the emulator knows, read from models/<CODE>/model.json.

This is the one place a model is described. Everything else gets it from here:

  models.py shell     bash assignments for engine/emu.sh (eval "$(python3 models.py shell)")
  models.py json      the list as JSON (the apps get it through `emu.sh info --json`)
  models.py note      one sentence on which firmware each model is set up with
  models.py header    engine/shim/models.h, the shim's product table
  models.py swift     Models.generated.swift for the Mac app
  models.py csharp    Models.generated.cs for the Windows app

Adding a model: a new folder with its model.json and panel.json (models/gen makes panels), then
`make -C engine/shim` and rebuild the apps. See docs/models.md for every field.
"""
import glob
import json
import os
import shlex
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load():
    out = []
    for f in sorted(glob.glob(os.path.join(HERE, "*", "model.json"))):
        with open(f, encoding="utf-8") as fh:
            m = json.load(fh)
        if m.get("code") != os.path.basename(os.path.dirname(f)):
            sys.exit(f"models: {f} has code {m.get('code')!r}; it has to match its folder")
        out.append(m)
    out.sort(key=lambda m: (m.get("order", 99), m["code"]))
    return out


def join_and(items):
    items = list(items)
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def join_or(items):
    items = list(items)
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " or " + items[-1]


def by_firmware(models):
    groups = {}
    for m in models:
        groups.setdefault(m["firmware"]["name"], []).append(m)
    return groups


def note(models):
    """'SC LIVE 4 and Prime 4+ decks are set up with the SC LIVE 4 firmware; a Prime 4 deck with
    Prime 4 firmware.'"""
    parts = []
    for i, (fw, ms) in enumerate(by_firmware(models).items()):
        names = [m["name"] for m in ms]
        if i == 0:
            deck = "decks are" if len(ms) > 1 else "deck is"
            parts.append(f"{join_and(names)} {deck} set up with the {fw} firmware")
        else:
            deck = "decks" if len(ms) > 1 else "deck"
            art = "" if len(ms) > 1 else "a "
            parts.append(f"{art}{join_and(names)} {deck} with {fw} firmware")
    return "; ".join(parts) + "."


def runs_as(models):
    """'the SC LIVE 4 firmware runs as an SC LIVE 4 or Prime 4+, Prime 4 firmware as a Prime 4'"""
    parts = []
    for i, (fw, ms) in enumerate(by_firmware(models).items()):
        names = join_or([m["name"] for m in ms])
        art = "an" if names[:1] in "AEIOUS" else "a"  # "an SC LIVE 4"
        parts.append(f"the {fw} firmware runs as {art} {names}" if i == 0 else f"{fw} firmware as {art} {names}")
    return ", ".join(parts)


def shell(models):
    q = shlex.quote
    lines = [f"MODEL_CODES={q(' '.join(m['code'] for m in models))}",
             f"MODEL_RUNS_AS={q(runs_as(models))}"]
    for m in models:
        c = m["code"]
        boards = [d for d in m["midi"]["devices"] if d.get("usb_pid")]
        lines += [
            f"model_{c}_name={q(m['name'])}",
            f"model_{c}_hostname={q(m.get('hostname', c))}",
            f"model_{c}_container={q(m['firmware']['container'])}",
            f"model_{c}_default={'1' if m['firmware'].get('default') else ''}",
            f"model_{c}_enginex={'1' if m.get('enginex') else ''}",
            f"model_{c}_efuse={'1' if m.get('efuse') else ''}",
            # "name:pid name:pid ..." with spaces in names as _
            f"model_{c}_boards={q(' '.join(d['board'].replace(' ', '_') + ':' + d['usb_pid'] for d in boards))}",
        ]
    return "\n".join(lines) + "\n"


def public(models):
    """What the apps need: code, name, which firmware, EngineX or not."""
    return [{"code": m["code"], "name": m["name"], "firmware": m["firmware"]["name"],
             "enginex": bool(m.get("enginex"))} for m in models]


def header(models):
    rows = []
    for m in models:
        a, mi = m["audio"], m["midi"]
        devs = ", ".join("{%d, \"%s\", 0x%02x, 0x%s}" % (d["client"], d["name"], d.get("tail", 0), d.get("usb_pid", "0"))
                         for d in mi["devices"])
        rows.append('    {"%s", "%s", "%s", %d, %d, 0x%02x, %d, {%s}},' % (
            m["code"], a["card"], a["pcm"], a["out_channels"], a["in_channels"], mi["family"], len(mi["devices"]), devs))
    return ("/* Generated by models/models.py header from each models/CODE/model.json. Don't edit; run\n"
            " * `make -C engine/shim` after changing a model. */\n"
            "static const struct fproduct g_products[] = {\n" + "\n".join(rows) + "\n};\n")


def swift(models):
    rows = ",\n".join(f'        DeckModel(code: {json.dumps(m["code"])}, name: {json.dumps(m["name"])}, ready: true)' for m in models)
    return ("// Generated by models/models.py swift (apps/mac/app/build.sh runs it). Don't edit.\n"
            "extension DeckModel {\n"
            f"    static let all: [DeckModel] = [\n{rows}\n    ]\n"
            f"    static let firmwareNote = {json.dumps(note(models))}\n"
            "}\n")


def csharp(models):
    codes = ", ".join(json.dumps(m["code"]) for m in models)
    names = ", ".join(json.dumps(m["name"]) for m in models)
    return ("// Generated by models/models.py csharp (apps/windows/build.sh runs it). Don't edit.\n"
            "namespace EngineOSEmulator\n{\n    static partial class DeckModels\n    {\n"
            f"        public static readonly string[] Codes = {{ {codes} }};\n"
            f"        public static readonly string[] Names = {{ {names} }};\n"
            f"        public const string FirmwareNote = {json.dumps(note(models))};\n"
            "    }\n}\n")


def main():
    what = sys.argv[1] if len(sys.argv) > 1 else "json"
    models = load()
    if what == "shell":
        sys.stdout.write(shell(models))
    elif what == "json":
        print(json.dumps(public(models)))
    elif what == "note":
        print(note(models))
    elif what == "header":
        sys.stdout.write(header(models))
    elif what == "swift":
        sys.stdout.write(swift(models))
    elif what == "csharp":
        sys.stdout.write(csharp(models))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
